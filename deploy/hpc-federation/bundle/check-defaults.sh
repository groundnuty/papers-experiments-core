#!/bin/bash
# check-defaults.sh: fail if an image default credential is still in place, or a secret has leaked.
# Files (node-init.sh runs this before the start):
#   private work and secrets directories; 0600 secret files; a 64-hex Erlang cookie in every service's
#   $HOME/.erlang.cookie, never 'cluster_node'; no -setcookie in the seed vm.args; env.sh patched so no
#   cookie reaches a command line; onepanel's Couchbase administrator overridden (not admin/password)
#   by our overlay alone, its password 24 alphanumerics (couchbase-cli's limit); none of the Couchbase cookies or memcached password shipped in the image;
#   every Erlang VM start path (relx env.sh and vm.args, couchbase-server) puts the distribution on
#   127.0.0.1 and uses the job's epmd; Couchbase's transient init and executioner nodes listen in
#   21100-21299; projector replaced by a stand-in that never listens; the Couchbase guard (the watcher of
#   the pre-admin window) started, and no Couchbase start of our own before onepanel's; the launcher waits for our own
#   listener on 9443.
# Live (--live; finish.sh / finish-zone.sh run it after the services are up) reads running values:
#   every listener of ours is on loopback unless it is public (8443; 6665 on a provider), and on loopback
#   it is held by a program whose accept() the shim's owner check sees (goxdcr's 9998 excepted, a known
#   residual); no UDP of ours but the zone's DNS on 8053; the ports our clients dial by number are ours,
#   our epmd is on the job's port (not 4369); other uids' listeners are listed (info);
#   no process of ours carries a secret or the default cookie on its command line; every Erlang node
#   answers a ping that uses the file cookie (the init.d status path onepanel itself uses) and refuses
#   one with 'cluster_node'; the vm.args onepanel rewrote hold no other cookie; Couchbase refuses
#   admin/password, every retired administrator password and an anonymous admin request, and accepts the current one; the live Couchbase
#   cookies and memcached password are not the shipped ones; the served web key is not the shipped one.
# Usage: check-defaults.sh <op|oz> --workdir W [--live]
# shellcheck disable=SC2016  # single-quoted '$HOME' below is literal text to look for
source "$(dirname "$0")/lib.sh"
component "${1:-}"; shift
[[ ${1:-} == --workdir ]] || die "usage: check-defaults.sh <op|oz> --workdir W [--live]"
W=$(find_workdir "$COMP" "${2:-}"); LIVE=${3:-}
[[ -z $LIVE || $LIVE == --live ]] || die "unknown option '$LIVE'"
R=$W/rootfs; S=$(secrets_dir "$W"); fails=0
fail() { printf 'FAIL: %s\n' "$*" >&2; fails=$((fails + 1)); }
check() { local what=$1; shift; if "$@"; then ok "$what"; else fail "$what"; fi; }
secret_file() { [[ -f $1 && ! -L $1 && -O $1 && $(mode_of "$1") == 600 ]]; }
absent() { [[ ! -e $1 ]]; }

check "work directory is private (0700)" is_private_dir "$W"
check "secrets directory is private (0700)" is_private_dir "$S"
for f in passphrase erlang-cookie couchbase-user couchbase-password; do check "$f is a 0600 file" secret_file "$S/$f"; done
PASS='' COOKIE='' CB_USER='' CB_PASS=''
read_secret PASS "$S/passphrase"; read_secret COOKIE "$S/erlang-cookie"
read_secret CB_USER "$S/couchbase-user"; read_secret CB_PASS "$S/couchbase-password"
pass_ok() { [[ $PASS =~ ^[0-9a-f]{48}$ ]]; }
cookie_ok() { [[ $COOKIE =~ ^[0-9a-f]{64}$ && $COOKIE != "$DEFAULT_ERLANG_COOKIE" ]]; }
cb_ok() { [[ $CB_USER != "$DEFAULT_CB_USER" && $CB_PASS != "$DEFAULT_CB_PASSWORD" ]] && cb_cred_ok "$CB_USER" "$CB_PASS"; }
check "passphrase is 48 random hex characters" pass_ok
check "Erlang cookie is 64 random hex characters, not the default" cookie_ok
check "Couchbase administrator is random, not admin/password, within couchbase-cli's limits (password: $CB_PASSWORD_LEN alphanumerics)" cb_ok

same_cookie() { secret_file "$1" && [[ $(<"$1") == "$COOKIE" ]]; }
for home in /root "/var/lib/$PANEL" "/var/lib/$WORKER" /var/lib/cluster_manager; do
  check "$home/.erlang.cookie holds this launch's cookie (0600)" same_cookie "$R$home/.erlang.cookie"
  check "$home has no XDG cookie that would shadow it" absent "$R$home/.config/erlang/.erlang.cookie"
done
no_seed_cookie() { ! grep -q '^-setcookie' "$1"; }
for svc in $SERVICES; do
  check "$svc env.sh keeps the cookie off command lines" grep -qF 'COOKIE_ARG=""  # hpcop: cookie from $HOME/.erlang.cookie' "$R/usr/lib/$svc/lib/env.sh"
  check "$svc seed vm.args has no -setcookie" no_seed_cookie "$R/volumes/persistence_backup/etc/$svc/autogenerated.vm.args"
done

overlay_ok() {  # our overlay holds the current administrator, and no other panel config file sets one
  local d o other
  d=$(config_dir "$R" "$PANEL"); o=$d/40-hpcop-couchbase.config
  secret_file "$o" || return 1
  [[ $(<"$o") == *"{couchbase_user, \"$CB_USER\"}, {couchbase_password, \"$CB_PASS\"}"* ]] || return 1
  other=$(grep -lE 'couchbase_(user|password)' -- "$d"/*.config "$R/etc/$PANEL/overlay.config" 2>/dev/null | grep -vxF "$o" || true)
  [[ -z $other ]]
}
check "onepanel's Couchbase administrator comes from our 0600 overlay only" overlay_ok
check "no shipped Couchbase cookie or memcached password under /volumes" no_baked "$R/volumes"
preload_ok() { [[ $(<"$R/etc/ld.so.preload") == /usr/local/lib/hpcop-portshim.so ]]; }
check "ld.so.preload loads only the shim" preload_ok
if [[ $COMP == op && -e $S/registration-token ]]; then check "registration token is a 0600 file" secret_file "$S/registration-token"; fi

# Every Erlang VM start path puts the distribution on loopback; `service` runs them under env -i, so each
# sources the Erlang env file itself (configure.sh writes it), and the vm.args carry it as a second layer.
ENVLINE="if [ -r $HPCOP_ERLANG_ENV ]; then . $HPCOP_ERLANG_ENV; fi"
sources_env() { [[ $(grep -cxF -- "$ENVLINE" "$1") == 1 ]]; }
relx_dist_ok() {  # <vm.args>
  grep -qxF -- '-kernel inet_dist_use_interface {127,0,0,1}' "$1" && grep -qxF -- '-kernel inet_dist_listen_min 9100' "$1" \
    && grep -qxF -- '-kernel inet_dist_listen_max 9139' "$1"
}
for svc in $SERVICES; do
  check "$svc env.sh (node and nodetool) sources the Erlang env file" sources_env "$R/usr/lib/$svc/lib/env.sh"
  check "$svc vm.args: distribution on 127.0.0.1, ports 9100-9139" relx_dist_ok "$R/var/lib/$svc/vm.args"
done
CBS=$R/opt/couchbase/bin/couchbase-server
babysitter_dist_ok() { grep -qF "inet_dist_listen_max 21299 inet_dist_use_interface '{127,0,0,1}'" "$CBS"; }
projector_ok() { grep -qxF 'exec /bin/sleep infinity' "$R/opt/couchbase/bin/projector" && ! grep -q 'hpcop-real' "$R/opt/couchbase/bin/projector"; }
check "couchbase-server (all Couchbase VMs, its epmd start) sources the Erlang env file" sources_env "$CBS"
check "couchbase-server: babysitter distribution on 127.0.0.1" babysitter_dist_ok
check "projector (Go, out of the shim's reach): a stand-in that never listens" projector_ok
transient_dist_ok() {  # the -sname init node and the -k executioner listen where the owner check applies
  grep -qF -- '-sname init -kernel inet_dist_listen_min 21100 inet_dist_listen_max 21299 -run init stop' "$CBS" \
    && grep -qF -- "-name executioner@executioner -kernel inet_dist_listen_min 21100 inet_dist_listen_max 21299 \\" "$CBS"
}
check "couchbase-server: the transient init and executioner nodes listen in 21100-21299" transient_dist_ok
launcher_wait_ok() { grep -qF 'sp.run(["python3", "-I", "/root/hpcop-cb-init.py", "--wait-listener", "9443", "1800"], check=True)' "$R/root/$START.py"; }
check "the launcher waits for onepanel's own listener on 9443" launcher_wait_ok
cb_init_ok() {  # the Couchbase guard runs (it measures the pre-admin window), and nothing provisions Couchbase before onepanel
  cmp -s -- "$HPCOP_BUNDLE/hpcop-cb-init.py" "$R/root/hpcop-cb-init.py" \
    && grep -qxF "$CB_WATCH_LINE" "$R/root/hpcop-start.sh" \
    && ! grep -q 'couchbase-server start' "$R/root/hpcop-start.sh"
}
check "hpcop-start.sh starts the Couchbase guard (hpcop-cb-init.py --watch, which may stop the start); onepanel's cluster-init sets the administrator" cb_init_ok
erlang_env_ok() {  # what configure.sh wrote: a job epmd port, epmd and distribution on loopback
  local f=$R$HPCOP_ERLANG_ENV p
  p=$(sed -n 's/^ERL_EPMD_PORT=\([0-9]*\)$/\1/p' "$f")
  [[ -n $p ]] && port_in "$p" "$HPCOP_EPMD_RANGE" && grep -qxF 'ERL_EPMD_ADDRESS=127.0.0.1' "$f" \
    && grep -qxF "ERL_AFLAGS='-kernel inet_dist_use_interface {127,0,0,1}'" "$f" \
    && grep -qxF 'export ERL_EPMD_PORT ERL_EPMD_ADDRESS ERL_AFLAGS' "$f"
}
if [[ -e $R$HPCOP_ERLANG_ENV || $LIVE == --live ]]; then
  check "Erlang env file: job epmd port in $HPCOP_EPMD_RANGE, epmd and distribution on 127.0.0.1" erlang_env_ok
fi

if [[ $LIVE == --live ]]; then
  need_tools ss   # the live check reads the node's listeners: without ss it would check nothing, so it never starts
  T=$(mktemp -d "$W/tmp/check.XXXXXX"); trap 'rm -rf -- "$T"' EXIT
  SECRETS=("$PASS" "$COOKIE" "$CB_PASS")
  RETIRED=()   # every password a rotation retired (a restart rotates again), not only the last
  while IFS= read -r v; do RETIRED+=("$v"); done < <(retired_passwords "$S")
  if (( ${#RETIRED[@]} )); then SECRETS+=("${RETIRED[@]}"); fi
  if [[ -s $S/registration-token ]]; then v=''; read_secret v "$S/registration-token"; SECRETS+=("$v"); fi
  argv_clean() {  # every process of ours: no secret and no default cookie on its command line
    local d cl s exe bad=0
    for d in /proc/[0-9]*; do
      [[ -O $d ]] || continue
      cl=$(tr '\0' ' ' < "$d/cmdline" 2>/dev/null) || continue
      for s in "${SECRETS[@]}"; do
        if [[ $cl == *"$s"* ]]; then   # report the executable only, never the command line itself
          exe=$(readlink -- "$d/exe" 2>/dev/null) || exe='?'
          printf 'FAIL: pid %s (%s) has a secret on its command line\n' "${d#/proc/}" "$exe" >&2; bad=1
        fi
      done
      if [[ $cl == *"-setcookie $DEFAULT_ERLANG_COOKIE"* ]]; then printf 'FAIL: pid %s runs with the default cookie\n' "${d#/proc/}" >&2; bad=1; fi
    done
    return "$bad"
  }
  check "no process of ours has a secret or the default cookie on its command line" argv_clean

  in_container() {  # with the service's own hosts file (hosts_bind), so its Erlang node names resolve as the service's do
    local -a naming=()
    hosts_bind "$W" naming
    apptainer exec --containall --no-home --pwd /root "${naming[@]}" "$R" /bin/bash -c ". $HPCOP_ERLANG_ENV; $1" < /dev/null 2>&1
  }
  live_vmargs_ok() {  # what onepanel wrote: no cookie, or ours in a 0600 file (env.sh drops it at start)
    local c; c=$(sed -n 's/^-setcookie //p' "$1")
    [[ -z $c || ( $c == "$COOKIE" && $(mode_of "$1") == 600 ) ]]
  }
  answers() { [[ $(in_container "env -i PATH=/usr/sbin:/usr/bin:/sbin:/bin /etc/init.d/$1 status") == *"is running"* ]]; }
  refuses_default() {  # <service> <node>
    local out
    out=$(in_container "E=\$(cut -d' ' -f1 /usr/lib/$1/releases/start_erl.data); HOME=/root /usr/lib/$1/erts-\$E/bin/escript /usr/lib/$1/erts-\$E/bin/nodetool -name $2 -setcookie $DEFAULT_ERLANG_COOKIE ping") || true
    [[ $out != *pong* ]]
  }
  for svc in $SERVICES; do
    va=$R/volumes/persistence/etc/$svc/autogenerated.vm.args
    node=$(sed -n 's/^-name //p' "$va" 2>/dev/null | head -n 1)
    [[ $node =~ ^[A-Za-z0-9_.@-]+$ ]] || { fail "$svc: no node name in the live vm.args"; continue; }
    check "$svc live vm.args holds no cookie but ours (0600)" live_vmargs_ok "$va"
    check "$svc ($node) answers a ping with the file cookie" answers "$svc"
    check "$svc ($node) refuses the default cookie" refuses_default "$svc" "$node"
  done

  cb_is() { [[ $(cb_status "$T" "$2" "$3") == "$1" ]]; }   # <status> <user> <password>
  check "Couchbase refuses admin/password" cb_is 401 "$DEFAULT_CB_USER" "$DEFAULT_CB_PASSWORD"
  check "Couchbase accepts the current administrator" cb_is 200 "$CB_USER" "$CB_PASS"
  anon_refused() { [[ $(http GET http://127.0.0.1:8091/settings/web "$T/anon.out") == 401 ]]; }   # cb_guard in lib.sh: why this endpoint
  check "Couchbase refuses an anonymous admin request (GET /settings/web: 401), so it has an administrator" anon_refused
  if (( ${#RETIRED[@]} )); then
    n=0
    for OLD in "${RETIRED[@]}"; do
      n=$((n + 1))
      check "Couchbase refuses retired administrator password $n of ${#RETIRED[@]}" cb_is 401 "$CB_USER" "$OLD"
    done
    unset OLD
  else
    fail "the deploy-time Couchbase password was never rotated"
  fi
  CB=$R/volumes/persistence/opt/couchbase/var/lib/couchbase
  babysitter_ok() { [[ -s $CB/couchbase-server.cookie && $(<"$CB/couchbase-server.cookie") != nocookie ]]; }
  key=$R/volumes/persistence/etc/$PANEL/certs/web_key.pem
  key_ok() { [[ -s $key ]] && ! cmp -s -- "$key" "$R/volumes/persistence_backup/etc/$PANEL/certs/web_key.pem"; }
  check "live Couchbase cookies and memcached password are not the shipped ones" no_baked "$CB"
  check "live babysitter cookie is set (not the nocookie placeholder)" babysitter_ok
  check "served web key is not the key shipped in the image" key_ok
  check "run.log is a 0600 file" secret_file "$W/run.log"

  # The network exposure, read from the node's own socket table after the start: every listener of
  # ours off loopback must be a public port (8443, and 6665 on a provider); every loopback TCP listener of
  # ours is owner-checked (held by a program whose accept() goes through the shim); our only UDP socket is
  # the zone's DNS; the ports our clients dial by number are ours; our epmd is on this job's port.
  EPMD=$(epmd_port_of "$R")
  live_ports_ok() { live_listeners_ok "$COMP" "$(id -u)" "$EPMD"; }   # a listing that fails is a FAIL (ports.sh)
  check "every listener of this service off loopback is public ($(public_ports "$COMP")), every loopback one owner-checked; epmd on 127.0.0.1:$EPMD" live_ports_ok
fi

(( fails == 0 )) || die "$fails default/secret check(s) failed"
ok "all default checks passed${LIVE:+ (live)}"
