mode_of() { stat -c %a -- "$1"; }
is_private_dir() { [[ -d $1 && ! -L $1 && -O $1 && $(mode_of "$1") == 700 ]]; }

check_tmpdir() {  # the job's $TMPDIR: absolute, and no other user can rename anything on its path
  local d owner m
  # A link was already replaced by the node's /tmp when this file was sourced (above); one set later fails here.
  d=${TMPDIR:-}
  [[ -n $d ]] || die "TMPDIR is not set: run inside a job on the compute node (Slurm sets a per-job TMPDIR)"
  [[ $d == /* ]] || die "TMPDIR '$d' is not absolute"
  while [[ $d != / ]]; do
    [[ -d $d && ! -L $d ]] || die "$d (on the path to TMPDIR) is not a plain directory"
    owner=$(stat -c %u -- "$d"); m=$(mode_of "$d")
    # HPCOP_TEST_TRUSTED_UID: offline tests only, in a user-namespaced sandbox where root shows as 65534.
    [[ $owner == "$(id -u)" || $owner == 0 || $owner == "${HPCOP_TEST_TRUSTED_UID:-0}" ]] \
      || die "$d is owned by uid $owner, neither you nor root"
    if (( 8#$m & 8#022 )) && [[ ! -k $d ]]; then die "$d is group- or world-writable without the sticky bit"; fi
    d=$(dirname -- "$d")
  done
}

make_workdir() {  # <label>: print a new private work directory under $TMPDIR, or refuse to run
  local d owner
  check_tmpdir
  owner=${HPCOP_OWNER_PID:-$$}
  if [[ ! $owner =~ ^[0-9]+$ ]] || ! alive "$owner"; then die "HPCOP_OWNER_PID '$owner' is not a running process"; fi
  d=$(mktemp -d "$TMPDIR/hpcop-$1.XXXXXX") || die "mktemp -d failed under $TMPDIR"
  chmod 700 -- "$d"
  is_private_dir "$d" || die "work directory $d is not private (uid $(stat -c %u -- "$d"), mode $(mode_of "$d"))"
  # Who owns it, for sweep_leftovers: the batch script that holds the job (HPCOP_OWNER_PID), or this
  # script, by PID and start time. While that process runs, no later job of ours removes the directory.
  printf '%s %s\n' "$owner" "$(proc_field "$owner" 22)" > "$d/owner.pid"
  printf '%s\n' "$d"
}

# A SIGKILL (Slurm's KillWait, after the stop has run out of time) can end the batch script before
# remove_workdir runs: the work directory then stays in the node-wide /tmp, holding the bucket data and
# Couchbase's own secrets, readable only by us and root. The next job of ours on the node removes it.
# A work directory a kept stop left (teardown.sh --keep) has no owner process, and must survive the next job's sweep:
# its keep-until mark (a regular file of ours, not a link, holding one integer: an epoch in seconds, the allocation's
# end) keeps it until that moment has passed.
keep_until_future() {  # <dir>: its keep-until mark is a valid epoch that is still in the future
  local f=$1/keep-until v
  [[ -f $f && ! -L $f && -O $f ]] || return 1
  v=$(<"$f") || return 1   # one trailing newline goes; a second line fails the pattern below
  [[ $v =~ ^[0-9]{1,15}$ ]] || return 1
  (( 10#$v > $(date +%s) ))
}

# A stop that keeps the work directory: stop-requested (teardown.sh --keep, or restart.sh after a failed restart)
# begins with the line 'keep'. Any other stop-requested (an empty file) is a stop that removes everything.
kept_stop() {  # <workdir>
  local f=$1/stop-requested first=''
  [[ -f $f && ! -L $f && -O $f ]] || return 1
  IFS= read -r first < "$f" || true
  [[ $first == keep ]]
}

leftover_owner_gone() {  # <dir>: its owner record names a process that is no longer running
  local pid='' start=''
  if keep_until_future "$1"; then return 1; fi   # kept until the allocation ends, whoever owned it
  [[ -f $1/owner.pid && ! -L $1/owner.pid && -O $1/owner.pid ]] || return 1   # no record: being made, keep
  read -r pid start < "$1/owner.pid" || true
  [[ $pid =~ ^[0-9]+$ && $start =~ ^[0-9]+$ ]] || return 1
  if alive "$pid" && [[ $(proc_field "$pid" 22) == "$start" ]]; then return 1; fi
}

safe_parents() {  # <path>: every directory above it is ours or root's, and none is writable by others without the sticky bit
  local d owner
  d=$(dirname -- "$1")
  while [[ $d != / ]]; do
    [[ -d $d && ! -L $d ]] || return 1
    owner=$(stat -c %u -- "$d")
    [[ $owner == "$(id -u)" || $owner == 0 || $owner == "${HPCOP_TEST_TRUSTED_UID:-0}" ]] || return 1
    if (( 8#$(mode_of "$d") & 8#022 )) && [[ ! -k $d ]]; then return 1; fi
    d=$(dirname -- "$d")
  done
}

sweep_leftovers() {  # remove the work directories of our earlier jobs on this node, and nothing else
  # Where: the shared /tmp (HPCOP_SHARED_TMP, for tests) to depth 3, which holds the site's per-job
  # TMPDIR=/tmp/<jobid>/<host> of every earlier job, and this job's TMPDIR. What: a directory named
  # hpcop-<label>.XXXXXX (as make_workdir names them), of our uid, 0700, not a link, under parents only
  # we or root can change, whose recorded owner process has ended.
  local roots=("${HPCOP_SHARED_TMP:-/tmp}") d n=0
  if [[ -n ${TMPDIR:-} && -d $TMPDIR && $TMPDIR != "${roots[0]}" ]]; then roots+=("$TMPDIR"); fi
  while IFS= read -r -d '' d; do
    [[ ${d##*/} =~ ^hpcop-[a-z0-9-]+\.[A-Za-z0-9]{6}$ ]] || continue
    if is_private_dir "$d" && safe_parents "$d" && leftover_owner_gone "$d"; then
      chmod -R u+rwX -- "$d" 2>/dev/null || true
      rm -rf --one-file-system -- "$d" 2>/dev/null || true
      if [[ -e $d ]]; then say "could not remove $d, the leftover of an earlier job"
      else say "removed $d, the leftover of an earlier job of ours"; n=$((n + 1)); fi
    fi
  done < <(find -P "${roots[@]}" -maxdepth 3 -type d -user "$(id -u)" -name 'hpcop-*.??????' -print0 -prune 2>/dev/null || true)
  ok "no leftover work directory of an earlier job ($n removed)"
}

find_workdir() {  # <comp> [explicit dir]: print this job's one private work directory for <comp>
  local d found=()
  if [[ -n ${2:-} ]]; then
    [[ $2 == */hpcop-"$1".?????? ]] || die "$2 is not an hpcop-$1 work directory"
    is_private_dir "$2" || die "$2 is not a private (0700) directory of yours"
    printf '%s\n' "$2"; return
  fi
  check_tmpdir
  shopt -s nullglob
  for d in "$TMPDIR"/hpcop-"$1".??????; do is_private_dir "$d" && found+=("$d"); done
  shopt -u nullglob
  (( ${#found[@]} == 1 )) || die "expected one private $TMPDIR/hpcop-$1.* directory, found ${#found[@]} (pass --workdir)"
  printf '%s\n' "${found[0]}"
}

wait_workdir() {  # <comp> <seconds> [explicit dir]: as find_workdir, waiting for node-init to make it
  local end=$((SECONDS + $2)) d
  while (( SECONDS < end )); do
    if d=$(find_workdir "$1" "${3:-}" 2>/dev/null); then printf '%s\n' "$d"; return; fi
    sleep 5
  done
  find_workdir "$1" "${3:-}"
}

remove_workdir() {  # <dir>: delete a private hpcop work directory, and nothing else
  local d=$1
  [[ -e $d ]] || return 0
  [[ $d == /*/hpcop-*.?????? && $d != *..* ]] || die "refusing to remove $d: not an hpcop work directory"
  [[ -z ${TMPDIR:-} || $d == "$TMPDIR"/hpcop-*.?????? ]] || die "refusing to remove $d: not under TMPDIR"
  is_private_dir "$d" || die "refusing to remove $d: not a private directory of yours"
  chmod -R u+rwX -- "$d" 2>/dev/null || true   # a read-only directory inside must not stop the removal
  rm -rf --one-file-system -- "$d"
  [[ ! -e $d ]] || die "could not remove $d"
}

gen_hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }   # <bytes>: random hex on stdout

ALNUM=ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789
gen_alnum() {  # <n>: n random characters of [A-Za-z0-9] on stdout, log2(62) = 5.95 bits each
  # Unbiased: a byte of 248 or more (4 x 62) is dropped, so each kept byte picks one of the 62 symbols evenly.
  # A fixed read (od -N), not `tr -dc ... </dev/urandom | head`, whose SIGPIPE would fail a pipefail script.
  local out='' b
  while (( ${#out} < $1 )); do
    for b in $(od -An -N"$(( $1 * 2 ))" -tu1 /dev/urandom); do
      if (( b < 248 && ${#out} < $1 )); then out+=${ALNUM:b % 62:1}; fi
    done
  done
  printf '%s' "$out"
}

# The Couchbase administrator: what every client of it in this image takes as it is.
# - couchbase-cli 4.5.1 allows a password of at most 24 characters (node.py:26, MAX_LEN_PASSWORD = 24). Over
#   that, cluster-init prints an error and returns, exit status 0, before its POST /settings/web: Couchbase is
#   left with no administrator and onepanel goes on (node.py:434-437; live run 3). It checks the username only
#   for being non-empty (node.py:430).
# - Its Basic header is 'Basic ' + strip(base64.encodestring(user:password)) (restclient.py:104-105).
#   encodestring breaks the line every 76 characters, which httplib then refuses ("Invalid header value"), so
#   user:password must stay within 57 bytes, one line of base64.
# - Couchbase 4.5.1 wants a password of at least 6 characters without control characters, and a username
#   without spaces, control characters or any of ()<>@,;:\"/[]?={}; it sets no maximum (menelaus_web.erl:
#   2506-2523, read from the image's menelaus_web.beam).
# - onepanel passes both on a shell command line and in an Erlang string; curl -K and our form body take them
#   raw. [A-Za-z0-9] needs no quoting anywhere; the user may also hold '.', '_' and '-'.
# So: 24 random alphanumerics (24 x log2(62) = 142.9 bits), and a user of at most 32 characters.
# Our own Basic headers never wrap: curl builds them from the -K file, Python with b64encode.
CB_PASSWORD_LEN=24
cb_cred_ok() {  # <user> <password>: both within every limit above
  [[ $1 =~ ^[A-Za-z0-9._-]{1,32}$ && $2 =~ ^[A-Za-z0-9]{$CB_PASSWORD_LEN}$ ]] && (( ${#1} + 1 + ${#2} <= 57 ))
}

put_secret() {  # <path> <value>: write a 0600 file atomically; printf is a builtin, so no argv sees it
  local p=$1 t
  [[ ! -L $p ]] || die "$p is a symlink"
  t="$p.tmp.$$"
  ( umask 077; printf '%s' "$2" > "$t" )
  chmod 600 -- "$t"
  mv -f -- "$t" "$p"
}

read_secret() {  # <var> <path>: the file's first line into <var>; the file must be ours, 0600, non-empty
  [[ -f $2 && ! -L $2 && -O $2 ]] || die "secret file $2 is missing or not yours"
  [[ $(mode_of "$2") == 600 ]] || die "secret file $2 is not mode 0600"
  IFS= read -r "$1" < "$2" || true
  [[ -n ${!1} ]] || die "secret file $2 is empty"
}

curl_auth_file() {  # <path> <user> <password>: a curl -K config holding Basic credentials, mode 0600
  [[ $2 =~ ^[A-Za-z0-9._-]+$ && $3 =~ ^[A-Za-z0-9]+$ ]] || die "credentials outside the safe character set"
  put_secret "$1" "user = \"$2:$3\""$'\n'
}

http() {  # <method> <url> <body-out> [curl options...]: print the HTTP status; transport errors are fatal
  local m=$1 u=$2 o=$3 code; shift 3
  code=$(curl -sS -X "$m" -o "$o" -w '%{http_code}' --connect-timeout 10 --max-time 120 "$@" "$u") \
    || die "curl $m $u: transport error"
  printf '%s' "$code"
}

need_2xx() {  # <status> <what> <body-file>: fail on anything but 2xx
  [[ $1 =~ ^2[0-9][0-9]$ ]] || die "$2: HTTP $1: $(head -c 300 -- "$3" 2>/dev/null | tr -cd '[:print:]')"
}

# <file> <path> [--default V]. A JSON null is no value: the default stands in for it, and without a default it exits
# JSONGET_NULL (3), never printing the word null; 2 is a field that is not there or a file that is not JSON.
JSONGET_NULL=3
jsonget() { "$HPCOP_PY" -I -B "$HPCOP_BUNDLE/jsonget.py" "$@"; }

# The node's FQDN: `hostname -f`, whether or not HPC_NODE_DOMAIN is set, when it is dotted; when it is one label,
# `<hostname -s>.<HPC_NODE_DOMAIN>` (nodefacts.py's node_name makes the same name, by the same rule: the driver puts the
# value in every step's environment). That name resolves nowhere on the node: write_names maps it to the node's address.
node_fqdn() {
  local f s d label='[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?'
  f=$(hostname -f)
  if [[ $f =~ ^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$ ]]; then printf '%s\n' "$f"; return; fi
  [[ $f =~ ^[A-Za-z0-9-]+$ ]] || die "hostname -f gave '$f', not a fully qualified name"
  d=${HPC_NODE_DOMAIN:-}
  [[ -n $d ]] || die "hostname -f gave the one-label name '$f', not a fully qualified name: set HPC_NODE_DOMAIN in site.env to the domain its FQDN is to carry"
  s=$(hostname -s)
  [[ $d =~ ^$label(\.$label)*$ && $s =~ ^$label$ && $(( ${#s} + 1 + ${#d} )) -le 253 ]] \
    || die "HPC_NODE_DOMAIN '$d' and hostname -s '$s' do not make a fully qualified name"
  printf '%s.%s\n' "$s" "$d"
}

valid() {  # <kind> <value>: validate one input before it reaches a file or a template
  case $1 in
    name) [[ $2 =~ ^[A-Za-z0-9][A-Za-z0-9_-]{0,39}$ ]] ;;
    fqdn) [[ $2 =~ ^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$ && ${#2} -le 253 ]] ;;
    mail) [[ $2 =~ ^[A-Za-z0-9._+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$ ]] ;;
    ip) [[ $2 =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ || $2 =~ ^[0-9A-Fa-f:]*:[0-9A-Fa-f:]*$ ]] ;;
    *) false ;;
  esac || die "invalid $1: '$2'"
}

secrets_dir() { printf '%s\n' "$1/rootfs/root/.hpcop"; }   # <workdir>: the 0700 secrets directory

config_dir() {  # <rootfs> <service>: host path of the service's config.d, behind the /etc/<service> link
  local t
  [[ -L $1/etc/$2 ]] || die "/etc/$2 is not a symlink in the rootfs (image changed?)"
  t=$(readlink -- "$1/etc/$2")
  [[ $t == "/volumes/persistence/etc/$2" ]] || die "/etc/$2 points to '$t', expected /volumes/persistence/etc/$2"
  printf '%s\n' "$1$t/config.d"
}

check_service_files() {  # <workdir>: what run_service needs on disk, refused with a message when it is not there
  local W=$1 S f
  S=$(secrets_dir "$W")
  [[ -e $W/rootfs.complete ]] || die "$W has no complete rootfs: run node-init.sh first"
  for f in passphrase erlang-cookie couchbase-user couchbase-password config.yaml env; do
    [[ -s $S/$f && $(mode_of "$S/$f") == 600 ]] || die "$S/$f is missing or not 0600: run node-init.sh and configure.sh"
  done
  if [[ $COMP == op && ! -s $S/registration-token ]]; then die "no registration token yet: deliver-token.sh first"; fi
}

# The shared imported trees a provider mounts (O59): configure.sh's `importstorage.py prepare` checks them and writes the
# work directory's list; the service binds exactly that list, read-only, and nothing else of the node's filesystems.
split_imports() {  # <imports-array> <other-array> args...: the --import=SPACE=PATH arguments, then every other one
  local -n _imports=$1 _others=$2
  local a
  shift 2
  _imports=() _others=()
  for a in "$@"; do
    if [[ $a == --import=* ]]; then _imports+=("$a"); else _others+=("$a"); fi
  done
}

# The names a service registers under (O73). A federation reached by the names its layout declares gives each service
# `--declared=NAME` (the zone's or the provider's own domain) and one `--host=NAME=ADDRESS` per service of the federation,
# itself included: configure.sh registers the service under NAME, makes its certificate for NAME, and writes the hosts file
# the service's cell is given in place of the node's own, so every peer's declared name resolves in it (an unresolved
# peer's name crashes the provider's lookup of it). Without them the service registers under the node's own name.
split_names() {  # <declared-array> <hosts-array> <other-array> args...: the --declared= and --host= arguments, then the rest
  local -n _declared=$1 _hosts=$2 _others=$3
  local a
  shift 3
  _declared=() _hosts=() _others=()
  for a in "$@"; do
    case $a in
      --declared=*) _declared+=("${a#--declared=}") ;;
      --host=*) _hosts+=("${a#--host=}") ;;
      *) _others+=("$a") ;;
    esac
  done
}

service_name() {  # <workdir>: the name this service is registered under: its declared name, else the node's own
  local f
  if [[ ! -e $1/declared-name ]]; then node_fqdn; return; fi
  [[ -f $1/declared-name && ! -L $1/declared-name ]] || die "$1/declared-name is not a regular file"
  f=$(head -n 1 -- "$1/declared-name")
  valid fqdn "$f"
  printf '%s\n' "$f"
}

write_names() {  # <workdir> <node fqdn> <node short name> <declared name> <peer-ip ...>: W/declared-name and W/hosts (O73)
  local W=$1 fqdn=$2 short=$3 declared=$4 entry n a own ip
  local -A addr_of=() name_of=() peer=()
  shift 4
  for entry in "${HOSTS[@]}"; do
    [[ $entry == *=* ]] || die "invalid --host '$entry': NAME=ADDRESS"
    n=${entry%%=*} a=${entry#*=}
    valid fqdn "$n"; valid ip "$a"
    [[ -z ${addr_of[$n]:-} ]] || die "--host lists the name '$n' twice"
    [[ -z ${name_of[$a]:-} ]] || die "--host lists the address '$a' under two names"
    addr_of[$n]=$a name_of[$a]=$n
  done
  own=${addr_of[$declared]:-}
  [[ -n $own ]] || die "--host does not list this service's own declared name '$declared'"
  for ip in "$@"; do
    [[ -n ${name_of[$ip]:-} ]] || die "the peer $ip has no declared name: its --host entry is missing"
    peer[$ip]=1
  done
  for a in "${!name_of[@]}"; do
    [[ $a == "$own" || -n ${peer[$a]:-} ]] || die "the declared name of $a is no listed peer: the shim would not move its 443"
  done
  if [[ ${COMP:-} == op ]]; then
    [[ -n ${addr_of[${ZONE:-}]:-} ]] || die "--host does not list the zone's declared name '${ZONE:-}'"
  fi
  {
    printf '# hpcop hosts for %s %s on %s, written %s\n' "$COMP" "$declared" "$fqdn" "$(date -u +%FT%TZ)"
    printf '127.0.0.1 localhost\n::1 localhost ip6-localhost ip6-loopback\n'
    printf '%s %s %s %s\n' "$own" "$fqdn" "$short" "$declared"   # the cluster's node names stay the node's own
    for n in $(printf '%s\n' "${!addr_of[@]}" | sort); do
      [[ $n == "$declared" ]] || printf '%s %s\n' "${addr_of[$n]}" "$n"
    done
  } > "$W/hosts"
  chmod 644 -- "$W/hosts"
  printf '%s\n' "$declared" > "$W/declared-name"
  chmod 644 -- "$W/declared-name"
}

import_binds() {  # <workdir>: the `apptainer exec` arguments that bind each listed tree read-only, one per line; none for none
  [[ -e $1/imports ]] || return 0
  "$HPCOP_PY" -I -B "$HPCOP_BUNDLE/importstorage.py" binds --workdir "$1"
}

# A provider's posix storage on the shared scratch filesystem (O57, HPC_STORAGE_ROOT): its job is given its own directory
# there (--storage=PATH, up's), configure.sh's `posixstorage.py prepare` checks it and records it in the work directory,
# and every start is given the same argument again (provider.sbatch's first, restart.sh's from `hpcfed.py start`) and
# binds it, writable, onto /volumes/posix only when the record names exactly that path. Without it the storage is the
# rootfs's own /volumes/posix, on the node's tmpfs, and the service is started as it always was.
split_storage() {  # <storage-var> <other-array> args...: the one --storage=PATH argument ('' for none), then every other one
  local -n _storage=$1 _rest=$2
  local a
  shift 2
  _storage='' _rest=()
  for a in "$@"; do
    if [[ $a == --storage=* ]]; then
      [[ -z $_storage ]] || die "a provider binds one posix storage: --storage= is given twice"
      _storage=$a
    else
      _rest+=("$a")
    fi
  done
}

storage_binds() {  # <workdir> [--storage=PATH]: the `apptainer exec` arguments that bind this start's storage, one per line
  if [[ -z ${2:-} ]]; then  # this start names no storage: none is bound, and a work directory that records one refuses
    if [[ -e $1/posix-storage || -L $1/posix-storage ]]; then
      die "the work directory records a posix storage on scratch, but this start names none: it is not started on the node's tmpfs instead"
    fi
    return 0
  fi
  "$HPCOP_PY" -I -B "$HPCOP_BUNDLE/posixstorage.py" binds --workdir "$1" "$2"
}

hosts_bind() {  # <workdir> <array name>: the `apptainer exec` arguments that put W/hosts in the place of /etc/hosts (O73)
  # Every container on a service's rootfs takes them: the service itself (run_service), the checks that ping its Erlang
  # nodes (check-defaults.sh) and the commands run beside it (exec.sh). A node name the site's DNS does not hold (a
  # one-label node with HPC_NODE_DOMAIN) resolves only through this file; none without one, as before.
  local -n _hb=$2
  _hb=()
  if [[ -e $1/hosts ]]; then _hb=(--no-mount bind-paths --bind "$1/hosts:/etc/hosts:ro"); fi
}

run_service() {  # <workdir> [--storage=PATH]: become the service (apptainer exec) in the foreground of this process
  local W=$1 R=$1/rootfs S epmd b storage=${2:-}
  local -a binds=()
  S=$(secrets_dir "$W")
  check_service_files "$W"
  command -v apptainer >/dev/null || die "apptainer not on PATH"
  epmd=$(epmd_port_of "$R")
  # Seconds before the bind, not minutes (node-init checked too, before the untar).
  if [[ ${HPCOP_SKIP_PORTCHECK:-0} == 1 ]]; then say "port check skipped (offline test)"; else ports_free "$COMP" "$epmd"; fi
  install -d -m 700 -- "$W/work"
  home_in "$W"   # apptainer's configuration and cache, and every other tool's, in the work directory: never ~
  b=$(import_binds "$W") || die "the shared imported trees of $W cannot be bound (see above): the service is not started"
  if [[ -n $b ]]; then mapfile -t binds <<<"$b"; fi
  b=$(storage_binds "$W" "$storage") || die "the posix storage of $W on scratch cannot be bound (see above): the service is not started"
  if [[ -n $b ]]; then mapfile -t -O "${#binds[@]}" binds <<<"$b"; fi
  "$HPCOP_PY" -I -B "$HPCOP_BUNDLE/supervise.py" check || die "$HPCOP_PY cannot use pidfds, which the service's stop needs"
  # exec keeps this PID for supervise.py, which stays visible in /proc under hidepid (apptainer's setuid starter, its
  # child, does not). teardown.sh signals it only while its start time (stat field 22) still matches.
  printf '%s %s\n' "$$" "$(proc_field "$$" 22)" > "$W/service.pid"
  # --containall: own PID, IPC and mount namespaces, clean environment; the node's network and name.
  # --workdir keeps the container's /tmp and /var/tmp inside the private work directory. A shared tree is a read-only
  # bind (`:ro`) of the list's, over the empty mountpoint configure.sh made in the rootfs, which the container cannot
  # write to. A provider's storage on scratch, when its job was given one, is the one writable bind: its own directory
  # there, over the rootfs's empty /volumes/posix. Nothing else of the node's filesystems is seen.
  # A federation of declared names (O73): the node's /etc/hosts, which the site binds into every cell, is replaced by the
  # file configure.sh wrote, listing every peer's declared name; --no-mount bind-paths drops the site's binds (and with
  # them /etc/localtime, which becomes the image's), and our file is bound read-only in the place of /etc/hosts.
  local -a naming=()
  hosts_bind "$W" naming
  exec "$HPCOP_PY" -I -B "$HPCOP_BUNDLE/supervise.py" run -- apptainer exec --writable --containall --no-home --pwd /root \
    --workdir "$W/work" "${naming[@]}" "${binds[@]}" "$R" /root/hpcop-start.sh > "$W/run.log" 2>&1 < /dev/null
}

# The Couchbase guard inside the container (hpcop-cb-init.py --watch) prints one of these into run.log: passed
# once this launch's administrator answers and anonymous admin REST is refused, FAILED (and the service is being
# stopped) when Couchbase has no administrator after onepanel's setup, or another one.
CB_GUARD_PASSED='hpcop: Couchbase guard passed'
CB_GUARD_FAILED='hpcop: Couchbase guard FAILED'
# hpcop-start.sh's line that starts the guard, with its own PID ($$, kept by the exec into the stock start
# script): the PID the guard sends SIGTERM to, whose trap stops every component (patch.sh, check-defaults.sh).
# shellcheck disable=SC2016  # $$ is literal text here
CB_WATCH_LINE='python3 -I /root/hpcop-cb-init.py --watch /root/.hpcop 1800 8091 $$ &'

redact_stream() {  # <workdir>: stdin to stdout with every plain and base64 form of this launch's secrets redacted
  local pat
  pat=$(mktemp "$1/tmp/redact.XXXXXX")
  secret_values_file "$1" "$pat"
  "$HPCOP_PY" -I -B "$HPCOP_BUNDLE/scrub.py" filter "$pat" || printf '(excerpt withheld: the redaction failed)'
  rm -f -- "$pat"
}

# The status codes behind the guard's verdict, as data: the guard (in the container) prints one `hpcop-evidence`
# line per request into run.log, and this copies them, unchanged, into the batch job's log on stdout, where the run's
# driver reads them back (run/evidence.py). The lines hold a check, a moment, a request and two numbers: no secret.
CB_EVIDENCE_LABEL='hpcop-evidence '
guard_evidence() {  # <run.log>
  grep -F "$CB_EVIDENCE_LABEL" "$1" 2>/dev/null | grep -E '^hpcop-evidence \{[ -~]{1,300}\}$' || true
}

wait_ready() {  # <workdir> <service pid> [timeout s] [fresh|restart]: until the stock launcher reports the service ready
  # fresh (the default): a new deployment, so the launcher must also have printed 'Congratulations! New'. restart: the
  # service started over an existing deployment, which prints no such line; the lock and the guard's verdict are
  # still required (run.log is rewritten by every start, so both belong to this launch).
  local W=$1 log=$1/run.log end=$((SECONDS + ${3:-1800})) mode=${4:-fresh}
  [[ $mode == fresh || $mode == restart ]] || die "wait_ready: mode '$mode' is neither fresh nor restart"
  while (( SECONDS < end )); do
    # Polled every second: the guard's verdict ends the start at once (the batch script then stops the service).
    if grep -qF "$CB_GUARD_FAILED" "$log" 2>/dev/null; then
      guard_evidence "$log"
      die "$(grep -m1 -F "$CB_GUARD_FAILED" "$log" | cut -c8-400 | tr -cd '[:print:]')"
    fi
    if [[ -e $W/rootfs/root/service-ready.lock ]]; then
      if [[ $mode == fresh ]]; then
        grep -q 'Congratulations! New' "$log" || die "the service marked itself ready without a fresh deployment (see $log)"
      fi
      grep -qF "$CB_GUARD_PASSED" "$log" \
        || die "the deployment finished, but the Couchbase guard never confirmed this launch's administrator (no '$CB_GUARD_PASSED' line in $log)"
      guard_evidence "$log"
      ok "deployment finished; $(grep -m1 -F "$CB_GUARD_PASSED" "$log" | cut -c8-300 | tr -cd '[:print:]')"; return 0
    fi
    if grep -qE 'ERROR: (Starting the container failed|Failed to start the container)' "$log" 2>/dev/null; then
      # An excerpt goes to the batch log, which outlives the job: redacted first (live run 3: onepanel's error
      # output carried the Couchbase credentials as a base64 Basic header).
      die "deployment failed: $(grep -E 'ERROR' "$log" | tail -n 3 | cut -c1-200 | redact_stream "$W")"
    fi
    alive "$2" || die "the service exited before it was ready (see $log)"
    sleep 1
  done
  die "timed out waiting for the deployment (see $log)"
}

# The readiness budget of a start, in whole seconds: the 1800 s wait_ready has always been given, or HPCOP_READY_SECONDS
# (a test shortens it). finish.sh spends it on wait_ready and then on wait_domain, so one deadline covers both.
ready_budget() {  # prints it; fails on anything that is not a whole number of seconds from 1 to 99999
  local s=${HPCOP_READY_SECONDS:-1800}
  [[ $s =~ ^[1-9][0-9]{0,4}$ ]] || die "HPCOP_READY_SECONDS is '$s', not a whole number of seconds from 1 to 99999"
  printf '%s\n' "$s"
}

# op_worker's /configuration, once it holds a domain. op_worker answers `domain` from the provider record it reads over
# its Onezone connection, so a start whose REST listener already answers can say null for a moment before that
# connection is up (live, a restart: the identity check ran 1.9 s before op_worker logged the connection, and compared the
# word null with the recorded domain of a service that had not changed). A null or empty domain is waited for, polling
# every HPCOP_POLL_S (1) s up to <deadline>, a SECONDS value: the end of the readiness budget, which the wait is part of.
# There is always one read, and the first non-empty domain ends the wait whatever it is: the identity check then compares
# it as ever, so another domain is refused as changed, with no wait. A field that is not there (or an answer that is not
# JSON) is not a connection coming up, and fails at once.
# DOMAIN_WAIT_S is how long it waited, in seconds with three decimals (as STOP_SECONDS is): from the first read to the
# answer that held a domain, and exactly 0.000 when the first read held it, so "no wait was needed" is not a measurement.
# The wait lengthens a restart's down time, so a restart's status reports it (status.sh, `domain_wait_s`).
DOMAIN_WAIT_S=0.000
wait_domain() {  # <tmpdir> <fqdn> <ca> <service pid> <deadline> <budget s>: leaves the answer in <tmpdir>/conf.json
  local code rc dom t0 ms waited=0
  DOMAIN_WAIT_S=0.000
  t0=$(date +%s%N)
  while :; do
    code=$(http GET "https://$2:8443/configuration" "$1/conf.json" --cacert "$3" --resolve "$2:8443:127.0.0.1")
    need_2xx "$code" "op_worker /configuration" "$1/conf.json"
    rc=0; dom=$(jsonget "$1/conf.json" domain) || rc=$?
    case $rc in
      0)
        if [[ -n $dom ]]; then
          if (( waited )); then
            ms=$(( ($(date +%s%N) - t0) / 1000000 ))
            DOMAIN_WAIT_S=$(printf '%d.%03d' "$((ms / 1000))" "$((ms % 1000))")
          fi
          return 0
        fi ;;
      "$JSONGET_NULL") ;;
      *) die "op_worker's /configuration has no readable domain field (jsonget status $rc, its message above)" ;;
    esac
    waited=1
    (( SECONDS < $5 )) || die "the provider's domain stayed null (or empty) in op_worker's /configuration for the readiness budget of $6 s: its Onezone connection did not come up, so its identity could not be checked"
    alive "$4" || die "the service exited before it reported its domain"
    sleep "${HPCOP_POLL_S:-1}"
  done
}

cb_status() {  # <tmpdir> <user> <password>: HTTP status of an authenticated GET on this node's Couchbase
  curl_auth_file "$1/cb.cfg" "$2" "$3"
  http GET http://127.0.0.1:8091/pools/default "$1/cb.out" -K "$1/cb.cfg"
  rm -f -- "$1/cb.cfg"
}

# The guard, from the host: Couchbase must have this launch's administrator and refuse anonymous admin REST.
# The anonymous request is the test that matters: with no administrator Couchbase 4.5 lets anyone act as one,
# so any credentials pass (menelaus_roles.erl:229-235 gives the anonymous caller the admin role until
# ns_config_auth says provisioned, ns_config_auth.erl:60). The endpoint is GET /settings/web, which needs
# {[settings], read} (menelaus_web.erl:360): once provisioned, an anonymous caller gets only bucket_sasl on each
# password-less bucket, which the onedata bucket is, and that role reads [pools] (so GET /pools/default answers
# it) but not [settings]; it is then refused with 401 (menelaus_auth.erl:321-336). The reply names the
# administrator (menelaus_web.erl:2373), which must be ours.
# One request's status as data, on stdout (the job's log): `hpcop-evidence {...}` in the guard's own format
# (hpcop-cb-init.py), read back by the run driver. <when> is one of the callers' fixed phrases, never a value.
cb_evidence() {  # <when> <request> <status> <expected>
  local when=$1 request=$2 code=$3 expected=$4
  [[ $when =~ ^[A-Za-z0-9\ \'.,-]+$ && $request =~ ^[A-Za-z0-9\ \(\)/-]+$ && $code =~ ^[0-9]{3}$ && $expected =~ ^[0-9]{3}$ ]] \
    || die "cb_evidence: a field is not in the shape of the guard's evidence line"
  printf 'hpcop-evidence {"check": "cb_guard", "when": "%s", "request": "%s", "status": %d, "expected": %d}\n' \
    "$when" "$request" "$((10#$code))" "$((10#$expected))"
}

cb_guard() {  # <tmpdir> <user> <password> <when>: fail unless both hold
  local code who anon
  curl_auth_file "$1/cb.cfg" "$2" "$3"
  code=$(http GET http://127.0.0.1:8091/settings/web "$1/cb-guard.out" -K "$1/cb.cfg")
  rm -f -- "$1/cb.cfg"
  cb_evidence "$4" "GET /settings/web (administrator)" "$code" 200
  [[ $code == 200 ]] || die "Couchbase guard ($4): GET /settings/web as this launch's administrator answered HTTP $code, not 200"
  who=$(jsonget "$1/cb-guard.out" username --default '')
  [[ -n $who ]] || die "Couchbase guard ($4): Couchbase has no administrator (GET /settings/web names none): anyone can act as one"
  [[ $who == "$2" ]] || die "Couchbase guard ($4): Couchbase's administrator is '$who', not this launch's"
  anon=$(http GET http://127.0.0.1:8091/settings/web "$1/cb-guard.out")
  cb_evidence "$4" "GET /settings/web (anonymous)" "$anon" 401
  [[ $anon == 401 ]] || die "Couchbase guard ($4): an anonymous GET /settings/web answered HTTP $anon, not 401: Couchbase lets anyone act as its administrator"
  rm -f -- "$1/cb-guard.out"
  ok "Couchbase guard ($4): this launch's administrator answers, and anonymous admin REST is refused (401)"
}

# Every password a rotation retired, one per line, never overwritten: a restart rotates again, and Couchbase must
# refuse them all. Builtins only (read, printf), so no argv sees one.
retired_passwords() {  # <secrets dir>: each retired password on its own line of stdout
  local f=$1/couchbase-password.retired v
  [[ -e $f ]] || return 0
  [[ -f $f && ! -L $f && -O $f && $(mode_of "$f") == 600 ]] || die "$f is not a 0600 file of yours"
  while IFS= read -r v || [[ -n $v ]]; do
    if [[ -n $v ]]; then printf '%s\n' "$v"; fi
  done < "$f"
}

append_retired() {  # <secrets dir> <password>: one more line, 0600, written atomically, the earlier lines kept
  local f=$1/couchbase-password.retired body='' v
  if [[ -e $f ]]; then   # read here, not through retired_passwords in a subshell: a refusal must stop the rotation
    [[ -f $f && ! -L $f && -O $f && $(mode_of "$f") == 600 ]] || die "$f is not a 0600 file of yours"
    while IFS= read -r v || [[ -n $v ]]; do
      if [[ -n $v ]]; then body+=$v$'\n'; fi
    done < "$f"
  fi
  put_secret "$f" "$body$2"$'\n'
}

# onepanel (service_couchbase) runs couchbase-cli cluster-init and bucket-create with the administrator
# password on their command lines while it deploys. That is the image's code, out of our reach, so the
# password it used is retired as soon as the deployment is done: a fresh one that no process ever saw
# replaces it in Couchbase (POST /settings/web) and in onepanel's overlay, and the old one must fail. A restart
# rotates again (finish.sh --restart): the retired list grows, and every entry must stay refused.
cb_rotate() {  # <workdir> <tmpdir>
  local S user old new code
  S=$(secrets_dir "$1")
  read_secret user "$S/couchbase-user"; read_secret old "$S/couchbase-password"
  [[ $(cb_status "$2" "$user" "$old") == 200 ]] || die "Couchbase does not accept the deploy-time administrator"
  new=$(gen_alnum "$CB_PASSWORD_LEN")
  cb_cred_ok "$user" "$new" || die "the new Couchbase password is outside couchbase-cli's limits"
  curl_auth_file "$2/cb-old.cfg" "$user" "$old"
  put_secret "$2/cb-web.form" "username=$user&password=$new&port=SAME"
  code=$(http POST http://127.0.0.1:8091/settings/web "$2/cb-web.out" -K "$2/cb-old.cfg" --data @"$2/cb-web.form")
  rm -f -- "$2/cb-old.cfg" "$2/cb-web.form"
  need_2xx "$code" "Couchbase administrator password change" "$2/cb-web.out"
  append_retired "$S" "$old"
  put_secret "$S/couchbase-password" "$new"
  write_cb_overlay "$1/rootfs" "$user" "$new"
  [[ $(cb_status "$2" "$user" "$new") == 200 ]] || die "Couchbase rejects the new administrator password"
  [[ $(cb_status "$2" "$user" "$old") == 401 ]] || die "Couchbase still accepts the retired password"
  ok "Couchbase administrator password rotated after the deployment"
  cb_guard "$2" "$user" "$new" "after the rotation"
}

secret_values_file() {  # <workdir> <out>: this launch's secret values, one per line, into a 0600 file
  local S f v
  S=$(secrets_dir "$1")
  ( umask 077; : > "$2" )
  for f in passphrase erlang-cookie couchbase-password registration-token; do
    v=''
    if [[ -s $S/$f ]]; then IFS= read -r v < "$S/$f" || true; fi
    if [[ -n $v ]]; then printf '%s\n' "$v" >> "$2"; fi
  done
  retired_passwords "$S" >> "$2"   # every retired password, not only the last
}

scrub_secrets() {  # <workdir>: once the service has stopped, delete every secret it held; logs stay, redacted
  local W=$1 R=$1/rootfs S pat nee CB home svc d left hits=()
  # The value and needle files sit in the work directory itself, which the search below does not cover.
  S=$(secrets_dir "$W"); pat=$W/scrub.values; nee=$W/scrub.needles
  CB=$R/volumes/persistence/opt/couchbase/var/lib/couchbase
  secret_values_file "$W" "$pat"
  "$HPCOP_PY" -I -B "$HPCOP_BUNDLE/scrub.py" needles "$pat" "$nee" || { rm -f -- "$pat" "$nee"; die "scrub.py could not list the secret forms"; }
  rm -rf -- "$S"
  for home in /root "/var/lib/$PANEL" "/var/lib/$WORKER" /var/lib/cluster_manager; do rm -f -- "$R$home/.erlang.cookie"; done
  if d=$(config_dir "$R" "$PANEL" 2>/dev/null); then rm -f -- "$d/40-hpcop-couchbase.config"; fi
  for svc in $SERVICES; do rm -f -- "$R/volumes/persistence/etc/$svc/autogenerated.vm.args"; done  # onepanel's -setcookie
  rm -f -- "$CB/couchbase-server.cookie" "$CB/couchbase-server.cookie-ns-server" "$CB/isasl.pw" \
    "$CB/config/config.dat" "$R/volumes/persistence/etc/$PANEL/certs/web_key.pem"
  # Anything else that still holds one of this launch's values, plain or base64-encoded (live run 3: run.log
  # kept base64(user:password) from onepanel's error output), wherever a running service writes; the image's own
  # files cannot hold a per-launch value. grep -F finds the candidates (fixed strings from scrub.py, read from a
  # file: no argv sees them); scrub.py redacts each text file in place and removes a binary one.
  local where=()
  for d in "$W/run.log" "$W/work" "$W/tmp" "$R/root" "$R/volumes" "$R/var" "$R/etc" "$R/tmp"; do
    if [[ -e $d ]]; then where+=("$d"); fi
  done
  if [[ -s $nee ]]; then
    mapfile -d '' -t hits < <(grep -rlZF -f "$nee" -- "${where[@]}" 2>/dev/null || true)
    if (( ${#hits[@]} )); then
      "$HPCOP_PY" -I -B "$HPCOP_BUNDLE/scrub.py" redact "$pat" "${hits[@]}" >&2 \
        || { rm -f -- "$pat" "$nee"; die "scrub.py failed on: ${hits[*]}"; }
    fi
    left=$(grep -rlF -f "$nee" -- "${where[@]}" 2>/dev/null || true)
    rm -f -- "$pat" "$nee"
    [[ -z $left ]] || die "secret values remain after the scrub in: $left"
  fi
  rm -f -- "$pat" "$nee"
  ok "secrets removed from $W (logs kept, every plain and base64 form of a secret redacted)"
}

write_cb_overlay() {  # <rootfs> <user> <password>: onepanel's Couchbase admin credentials, mode 0600
  local d
  cb_cred_ok "$2" "$3" || die "Couchbase administrator outside couchbase-cli's limits (see cb_cred_ok)"
  d=$(config_dir "$1" "$PANEL")
  mkdir -p -- "$d"
  put_secret "$d/40-hpcop-couchbase.config" \
    "% hpcop: per-launch Couchbase administrator (replaces the image's admin/password)."$'\n'"[{onepanel, [{couchbase_user, \"$2\"}, {couchbase_password, \"$3\"}]}]."$'\n'
}
