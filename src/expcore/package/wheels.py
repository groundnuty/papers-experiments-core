# Provenance: new
"""The wheels a replication package ships, so that its `make check` installs the environment offline (#45, #46).

A package holds one wheel per distribution of the environment its replay check ran under (`provenance.environment`):
the core, the study's platform and backend packages, and everything they require. `make check` installs them into a
fresh environment with `pip install --no-index --no-deps --require-hashes`, from `wheels/requirements.txt`, which
pins each wheel by name, version and SHA-256, so the reader needs neither the network nor an index. pip runs isolated
(`--isolated`, which ignores its environment variables and the user's configuration, and `PIP_CONFIG_FILE=/dev/null`,
which skips every configuration file): a `PIP_REQUIREMENT` or a configured requirement could otherwise add a URL to
fetch.

Where a wheel comes from, for each distribution:
- a wheel the author supplies (`--wheels DIR`), named `<name>-<version>-<tags>.whl` with that name and version in
  its metadata, is taken byte for byte, once its code is shown to be what is installed: the way to ship a public
  release's own wheel, or the wheel of a distribution installed editable. Each member outside its `.dist-info` must
  match the installed file its RECORD lists (by hash), and every installed file must be in it; for an editable install,
  each member must match the file of the checkout it imports from, found below a directory its `.pth` puts on the
  path (or through its RECORD), and every Python file of the checkout under a package the wheel holds must be in it.
  A member with no counterpart there (an example data file the build maps in) cannot be compared: it goes in and is
  listed in `PACKAGE.json`. A wheel whose code differs is refused, naming the member;
- otherwise the installed files are packed again into a wheel: every file the distribution's RECORD lists inside
  the site directory, each checked against its RECORD hash, without bytecode and without what the installer added
  (INSTALLER, REQUESTED, RECORD, direct_url.json and the installer's own records); RECORD is written anew. The wheel
  is deterministic: entries sorted, dated 1980-01-01, mode 0644 or 0755. Files installed outside the site directory
  (console scripts, which the installer writes again from the entry points, and data files) are left out;
- a distribution installed editable is refused: its installed files are a pointer to a checkout, not its code.

A wheel is built for the platform and the Python of the build, as installed; the package says which, and a reader
needs the same. Every text member of every wheel is read by the package's checks, and every other member (a
compiled extension) is attested by its hash (`wheelscan`); `from_index` says whether the wheel was packed from an
index install, a release whose text is read as it is, rather than the author's own code, which is read with every
view the checks have. `direct` says whether the distribution was installed from a URL, a repository or a directory,
whichever way its wheel was made: such a wheel always gets the study-token list (`lockfile`). A wheel packed again is
never the published artifact's bytes, so only a supplied wheel can be the release a lock records.
"""

import base64
import hashlib
import io
import re
import stat
import zipfile
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from email.parser import HeaderParser
from importlib import metadata
from pathlib import Path, PurePosixPath
from typing import Any

from expcore.package.spec import WHEELS_DIR, PackageError
from expcore.provenance.environment import (
    EnvironmentUnknown,
    canonical,
    editable_roots,
    installed,
    pth_directories,
    python_files,
    source_of,
)

REQUIREMENTS = f"{WHEELS_DIR}/requirements.txt"
ZIP_DATE = (1980, 1, 1, 0, 0, 0)
MAKEFILE = """\
# Generated by `python -m expcore package`. `make -f Makefile check` makes a fresh environment beside this directory
# ($(VENV)) with Python {python}, installs into it the wheels in wheels/ and nothing else (no index, no network), then
# verifies every file against SHA256SUMS and the environment against the one the replay check ran under, derives
# out/export.json, out/scores.json, out/analysis.json and out/report.md anew from the records in out/runs, and
# compares them with the shipped files byte for byte. `make -f Makefile check-installed PYTHON=...` runs the same
# check with an interpreter that already holds the environment PACKAGE.json names.
PYTHON ?= python3
VENV ?= $(CURDIR).venv

.PHONY: check check-installed environment
check: environment
\t"$(VENV)/bin/python" -m expcore package-check .

environment:
\t$(PYTHON) -c 'import sys; sys.exit(sys.version_info[:2] != ({major}, {minor}) and "this needs Python {python}")'
\t$(PYTHON) -m venv --clear "$(VENV)"
\tPIP_CONFIG_FILE=/dev/null "$(VENV)/bin/python" -m pip install --isolated --quiet --disable-pip-version-check \\
\t\t--no-index --no-deps --require-hashes --find-links wheels -r {requirements}

check-installed:
\t$(PYTHON) -m expcore package-check .
"""
INSTALLER_FILES = frozenset({"INSTALLER", "REQUESTED", "RECORD", "direct_url.json", "RECORD.jws", "RECORD.p7s"})
_INSTALLER_RECORD = re.compile(r"(uv|pip)_[A-Za-z0-9_]*\.json")


@dataclass(frozen=True)
class Wheel:
    """One vendored wheel: its distribution, its file name and bytes, whether it was packed from an index install, and
    whether its distribution was installed from a URL, a repository or a directory (`direct`), supplied or not."""

    name: str
    version: str
    filename: str
    data: bytes
    from_index: bool
    uncompared: tuple[str, ...] = ()  # members of a supplied wheel with no installed counterpart to compare
    direct: bool = False

    @property
    def path(self) -> str:
        return f"{WHEELS_DIR}/{self.filename}"

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.data).hexdigest()


Vendor = Callable[[Mapping[str, str], "Path | None"], Sequence[Wheel]]


def _escaped(name: str) -> str:
    return re.sub(r"[-_.]+", "_", name).lower()


def _wheel_tag(wheel_file: str, name: str) -> str:
    """The compressed tag set of an installed wheel's `Tag:` lines, as a wheel's file name carries it."""
    tags = [line.split(":", 1)[1].strip() for line in wheel_file.splitlines() if line.startswith("Tag:")]
    if not tags or any(tag.count("-") != 2 for tag in tags):
        raise PackageError(f"{name}: its installed WHEEL file names no tag, so no wheel can be built for it")
    parts = [list(dict.fromkeys(tag.split("-")[i] for tag in tags)) for i in range(3)]
    return "-".join(".".join(part) for part in parts)


def _record_hash(data: bytes) -> str:
    return "sha256=" + base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode("ascii")


def _kept(path: PurePosixPath, info_dir: str) -> bool:
    """Whether an installed file belongs in the wheel: inside the site directory, not bytecode, not the installer's."""
    if path.parts[0] == ".." or "__pycache__" in path.parts or path.suffix in (".pyc", ".pyo"):
        return False
    if path.parts[0] == info_dir and len(path.parts) == 2:
        return path.name not in INSTALLER_FILES and not _INSTALLER_RECORD.fullmatch(path.name)
    return True


def zip_entries(entries: Sequence[tuple[str, bytes, bool]]) -> bytes:
    """A deterministic zip of (name, bytes, executable) entries, in the order given."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for name, data, executable in entries:
            info = zipfile.ZipInfo(name, date_time=ZIP_DATE)
            info.create_system = 3  # unix, so the mode below is read
            info.external_attr = ((0o755 if executable else 0o644) | stat.S_IFREG) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data)
    return buffer.getvalue()


def repack(dist: metadata.Distribution) -> tuple[str, bytes]:
    """Pack an installed distribution's files into a wheel again; return its file name and bytes."""
    name, version = canonical(dist.metadata["Name"]), str(dist.version)
    files = dist.files
    info_dirs = {f.parts[0] for f in files or [] if f.parts and f.parts[0].endswith(".dist-info")}
    if not files or len(info_dirs) != 1:
        raise PackageError(f"{name}: its installed files are not listed (no RECORD), so no wheel can be built for it")
    info_dir = info_dirs.pop()
    entries: list[tuple[str, bytes, bool]] = []
    for item in sorted(files, key=lambda f: f.as_posix()):
        path = PurePosixPath(item.as_posix())
        if not _kept(path, info_dir):
            continue
        located = Path(str(dist.locate_file(item)))
        try:
            data = located.read_bytes()
        except OSError:
            raise PackageError(f"{name}: its installed file {path} cannot be read; reinstall {name}") from None
        if item.hash is not None and _record_hash(data) != f"{item.hash.mode}={item.hash.value}":
            raise PackageError(f"{name}: its installed file {path} differs from its RECORD; reinstall {name}")
        entries.append((path.as_posix(), data, bool(located.stat().st_mode & 0o111)))
    meta = [e for e in entries if e[0].startswith(f"{info_dir}/")]
    wheel_file = next((e[1] for e in meta if e[0] == f"{info_dir}/WHEEL"), None)
    if wheel_file is None:
        raise PackageError(f"{name}: it has no installed WHEEL file, so no wheel can be built for it")
    ordered = [e for e in entries if e not in meta] + meta
    record = "".join(f"{n},{_record_hash(d)},{len(d)}\n" for n, d, _ in ordered) + f"{info_dir}/RECORD,,\n"
    ordered.append((f"{info_dir}/RECORD", record.encode("utf-8"), False))
    tag = _wheel_tag(wheel_file.decode("utf-8"), name)
    return f"{_escaped(name)}-{version.replace('-', '_')}-{tag}.whl", zip_entries(ordered)


def _metadata_of(data: bytes) -> tuple[str, str] | None:
    """The name and version a wheel's METADATA gives; None when it has none."""
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            found = [n for n in archive.namelist() if re.fullmatch(r"[^/]+\.dist-info/METADATA", n)]
            if len(found) != 1:
                return None
            headers = HeaderParser().parsestr(archive.read(found[0]).decode("utf-8"))
    except (zipfile.BadZipFile, UnicodeDecodeError, KeyError):
        return None
    return canonical(headers.get("Name", "")), headers.get("Version", "")


def supplied_wheel(directory: Path, name: str, version: str) -> tuple[str, bytes] | None:
    """The author's wheel of this distribution and version in `directory`; None when there is none."""
    matches = []
    for path in sorted(Path(directory).glob("*.whl")):
        parts = path.name.split("-")
        if len(parts) >= 5 and canonical(parts[0]) == name and parts[1] == version.replace("-", "_"):
            matches.append(path)
    if not matches:
        return None
    if len(matches) > 1:
        raise PackageError(f"{directory}: holds {len(matches)} wheels of {name} {version}; leave one")
    data = matches[0].read_bytes()
    if _metadata_of(data) != (name, version):
        raise PackageError(f"{matches[0].name}: its metadata does not name {name} {version}")
    return matches[0].name, data


_DATA_IN_SITE = re.compile(r"[^/]+\.data/(?:purelib|platlib)/(.+)")


def code_members(data: bytes) -> dict[str, bytes]:
    """A wheel's files as they install into the site directory, outside its `.dist-info`."""
    found = {}
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        for name in archive.namelist():
            first = name.split("/", 1)[0]
            if name.endswith("/") or first.endswith(".dist-info"):
                continue
            if first.endswith(".data"):
                inside = _DATA_IN_SITE.fullmatch(name)
                if inside is None:
                    continue  # scripts, headers and data install outside the site directory
                found[inside.group(1)] = archive.read(name)
            else:
                found[name] = archive.read(name)
    return found


def _installed_files(dist: metadata.Distribution) -> dict[str, Any]:
    """The installed files of a distribution inside the site directory, by path, without bytecode or its metadata."""
    files = {}
    for item in dist.files or []:
        path = PurePosixPath(item.as_posix())
        if path.parts and not path.parts[0].endswith(".dist-info") and _kept(path, ""):
            files[path.as_posix()] = item
    return files


def _same_as_record(dist: metadata.Distribution, item: Any, data: bytes) -> bool:
    if item.hash is not None:
        return _record_hash(data) == f"{item.hash.mode}={item.hash.value}"
    located = Path(str(dist.locate_file(item)))
    return located.is_file() and located.read_bytes() == data


def compare_supplied(dist: metadata.Distribution, editable: bool, filename: str, data: bytes) -> tuple[str, ...]:
    """Refuse a supplied wheel whose code is not what is installed; return its members with nothing to compare."""
    members = code_members(data)
    record = _installed_files(dist)
    roots = editable_roots(dist) if editable else []
    uncompared = []
    for member, content in sorted(members.items()):
        local = next((root / member for root in roots if (root / member).is_file()), None)
        if local is not None:
            same = local.read_bytes() == content
        elif member in record and not member.endswith(".pth"):
            same = _same_as_record(dist, record[member], content)
        elif editable:
            uncompared.append(member)
            continue
        else:
            raise PackageError(f"{filename}: {member} is in the wheel but not installed; supply the installed wheel")
        if not same:
            raise PackageError(
                f"{filename}: {member} differs from the installed one; supply the wheel of what is installed"
            )
    for path in _expected(dist, editable, roots, members, record):
        if path not in members:
            raise PackageError(f"{filename}: lacks {path}, which is installed; supply the wheel of what is installed")
    return tuple(uncompared)


def _expected(dist: metadata.Distribution, editable: bool, roots: list[Path], members, record) -> list[str]:
    """What a supplied wheel must hold: every installed file, or for an editable install every Python file of the
    directories its `.pth` puts on the path; below a project directory, only those under a package the wheel holds."""
    if not editable:
        return [path for path in record if not path.endswith(".pth")]
    whole = bool(pth_directories(dist))
    tops = {member.split("/", 1)[0] for member in members if "/" in member}
    found = [p.relative_to(root).as_posix() for root in roots for p in python_files(root)]
    return [path for path in found if whole or path.split("/", 1)[0] in tops]


def vendor_wheels(distributions: Mapping[str, str], supplied: Path | None = None) -> list[Wheel]:
    """One wheel per distribution of the environment, from `supplied` or the installed files, as described above."""
    found = installed()
    wheels = []
    for name, version in sorted(distributions.items()):
        dist = found.get(name)
        if dist is None or str(dist.version) != version:
            raise PackageError(
                f"{name} {version} is in the environment the check ran under but not installed here; build the "
                "package in the campaign's environment"
            )
        try:
            source = source_of(dist)
        except EnvironmentUnknown as error:
            raise PackageError(str(error)) from None
        given = supplied_wheel(supplied, name, version) if supplied is not None else None
        if given is None and source is not None and source.get("editable"):
            raise PackageError(
                f"{name} is installed editable, so its installed files are not its code; build its wheel (for example "
                "`uv build --wheel --out-dir DIR` in its project) and pass `--wheels DIR`"
            )
        editable = bool(source and source.get("editable"))
        uncompared = compare_supplied(dist, editable, *given) if given is not None else ()
        filename, data = given or repack(dist)
        from_index = source is None and given is None
        wheels.append(
            Wheel(
                name, version, filename, data, from_index=from_index, uncompared=uncompared, direct=source is not None
            )
        )
    return wheels


def makefile(env: Mapping[str, Any]) -> bytes:
    """The package's Makefile for the Python of the environment."""
    major, minor = env["python"].split(".")
    return MAKEFILE.format(python=env["python"], major=major, minor=minor, requirements=REQUIREMENTS).encode("utf-8")


def requirements(wheels: Sequence[Wheel]) -> bytes:
    """`wheels/requirements.txt`: each wheel pinned by name, version and hash, for `pip --require-hashes`."""
    lines = ["# Generated by `python -m expcore package`: `make check` installs exactly these, from wheels/ only.\n"]
    lines += [f"{w.name}=={w.version} --hash=sha256:{w.sha256}\n" for w in sorted(wheels, key=lambda w: w.name)]
    return "".join(lines).encode("utf-8")


